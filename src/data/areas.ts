export function getNextAreaTransition(
  current: AreaCode,
  currentLoop: number,
): { areaCode: AreaCode; loop: number } {
  const def = AREAS[current];
  if (current === '0-1' || current === 'hq-3') {
    return { areaCode: '1-1', loop: currentLoop + 1 };
  }
  return { areaCode: def.nextArea, loop: currentLoop };
}
