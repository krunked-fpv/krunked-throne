export function getWeaponDef(id: string): WeaponDef {
  return WEAPONS[id] ?? WEAPONS.revolver!;
}

export function getWeaponsByTier(minTier: number, maxTier: number, includeCursed = false): WeaponDef[] {
  return WEAPON_LIST.filter(
    (weapon) =>
      weapon.tier >= minTier &&
      weapon.tier <= maxTier &&
      (includeCursed || !weapon.cursed),
  );
}
