import type { AmmoType, ProjectileKind, WeaponDef } from '@/contracts';

interface WeaponSpecInput {
  id: string;
  numericId: number;
  name: string;
  ammoType: AmmoType;
  ammoCost?: number;
  tier: number;
  reloadTicks: number;
  spreadDeg: number;
  kick: number;
  shake: number;
  burstCount?: number;
  burstIntervalTicks?: number;
  projectilesPerShot?: number;
  damage: number;
  projectileSpeed: number;
  projectileKind: ProjectileKind;
  projectileLifeTicks?: number;
  pierce?: number;
  bounce?: number;
  explosionRadius?: number;
  meleeReach?: number;
  meleeArcDeg?: number;
  deflectsProjectiles?: boolean;
  destroysProjectiles?: boolean;
  auto?: boolean;
  golden?: boolean;
  cursed?: boolean;
  ultra?: boolean;
  radCost?: number;
  sprite: string;
  projectileSprite?: string;
  fireSound: string;
  tip?: string;
}

function w(spec: WeaponSpecInput): WeaponDef {
  return {
    id: spec.id,
    numericId: spec.numericId,
    name: spec.name,
    ammoType: spec.ammoType,
    ammoCost: spec.ammoCost ?? (spec.ammoType === 'melee' ? 0 : 1),
    tier: spec.tier,
    reloadTicks: spec.reloadTicks,
    spreadDeg: spec.spreadDeg,
    kick: spec.kick,
    shake: spec.shake,
    burstCount: spec.burstCount ?? 1,
    burstIntervalTicks: spec.burstIntervalTicks ?? 0,
    projectilesPerShot: spec.projectilesPerShot ?? 1,
    damage: spec.damage,
    projectileSpeed: spec.projectileSpeed,
    projectileKind: spec.projectileKind,
    projectileLifeTicks: spec.projectileLifeTicks ?? 65,
    pierce: spec.pierce ?? 0,
    bounce: spec.bounce ?? 0,
    explosionRadius: spec.explosionRadius ?? 0,
    meleeReach: spec.meleeReach ?? 0,
    meleeArcDeg: spec.meleeArcDeg ?? 0,
    deflectsProjectiles: spec.deflectsProjectiles ?? false,
    destroysProjectiles: spec.destroysProjectiles ?? false,
    auto: spec.auto ?? false,
    golden: spec.golden,
    cursed: spec.cursed,
    ultra: spec.ultra,
    radCost: spec.radCost,
    sprite: spec.sprite,
    projectileSprite: spec.projectileSprite,
    fireSound: spec.fireSound,
    tip: spec.tip,
  };
}

