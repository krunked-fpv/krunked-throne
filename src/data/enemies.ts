export function getEnemyDef(id: string): EnemyDef | undefined {
  return ENEMIES[id];
}

export function getEnemiesForBiome(biome: BiomeId, loop: number = 0): EnemyDef[] {
  return Object.values(ENEMIES).filter(
    (e) =>
      !e.isBoss &&
      e.biomes.includes(biome) &&
      e.aiArchetype !== 'mimic' &&
      (!e.loopOnly || loop > 0),
  );
}
